"""exp-003: per-subroutine Toffoli accounting of the official sample dqi circuit.

Self-contained private Kaggle script kernel (generated by build_kernel.py, which inlines
src/kmx_tag_count.py as COUNTER_SRC). It never calls any Kaggle API and never submits.

Steps (each in its own child process, memory sampled by the parent):
  sample_count  load sample dqi.kmb, record stats + canonical sha256, dump .kmx, run the tag counter
  gen_compare   build dqi_reference_circuit.build_reference_circuit(4095, 70, 12) with kickmix 1.0.0,
                compare to the sample (==, canonical sha256, op counts), run the tag counter on it
  dqi_salt_*    unmodified official verifier on the sample, --salt exp003-a / -b / -c
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import platform
import subprocess
import sys
import threading
import time
from pathlib import Path

ON_KAGGLE = Path('/kaggle/working').is_dir()
POLL_S = 0.5
KICKMIX_PIN = 'kickmix==1.0.0'
SALTS = ['exp003-a', 'exp003-b', 'exp003-c']
OUT = Path(os.environ.get('EXP003_OUT') or ('/kaggle/working/exp003' if ON_KAGGLE else 'exp003_local_out')).resolve()
TMP = Path(os.environ.get('EXP003_TMP') or ('/tmp/exp003' if ON_KAGGLE else 'exp003_local_tmp')).resolve()

COUNTER_SRC = __COUNTER_SRC__


def find_data_root() -> Path:
    marker = Path('verifiers') / 'dqi' / 'verify_submission_dqi.py'
    for dirpath, dirnames, _ in os.walk('/kaggle/input'):
        if (Path(dirpath) / marker).is_file():
            return Path(dirpath)
        if dirpath.count(os.sep) > 6:
            dirnames[:] = []
    raise FileNotFoundError('competition data not found under /kaggle/input')


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 22), b''):
            h.update(chunk)
    return h.hexdigest()


def canonical_sha(circuit) -> str:
    # Same method as verify_submission_dqi.py _circuit_sha256.
    buf = io.BytesIO()
    circuit.to_file(buf, format='kmb')
    return hashlib.sha256(buf.getvalue()).hexdigest()


def load_counter():
    import types
    mod = types.ModuleType('kmx_tag_count')
    exec(compile(COUNTER_SRC, 'kmx_tag_count.py', 'exec'), mod.__dict__)
    return mod


def stats_dict(circuit) -> dict:
    s = circuit.operation_statistics()
    return {'num_qubits': circuit.num_qubits, 'num_bits': circuit.num_bits,
            'num_toffoli_like': s.num_toffoli_like, 'num_t_like': s.num_t_like,
            'num_instructions': s.num_instructions, 'op_counts': dict(s)}


def tag_count(circuit, name: str) -> dict:
    counter = load_counter()
    TMP.mkdir(parents=True, exist_ok=True)
    kmx = TMP / f'{name}.kmx'
    t0 = time.time()
    circuit.to_file(str(kmx), format='kmx')
    t1 = time.time()
    size = kmx.stat().st_size
    res = counter.count(str(kmx))
    t2 = time.time()
    kmx.unlink()
    res['kmx_bytes'] = size
    res['kmx_write_s'] = round(t1 - t0, 1)
    res['count_s'] = round(t2 - t1, 1)
    return res


def step_sample_count(data: Path) -> None:
    import kickmix as km
    path = data / 'sample_submission' / 'dqi.kmb'
    t0 = time.time()
    c = km.Circuit.from_file(str(path))
    info = {'file_sha256': sha256_file(path), 'load_s': round(time.time() - t0, 1),
            'canonical_sha256': canonical_sha(c), **stats_dict(c)}
    res = tag_count(c, 'sample')
    assert res['total_toffoli_like'] == info['num_toffoli_like'], (res['total_toffoli_like'], info)
    res['circuit_info'] = info
    (OUT / 'sample_count.json').write_text(json.dumps(res, indent=1))
    print(json.dumps({'sample': info['num_toffoli_like'], 'q': info['num_qubits'],
                      'tag_total': res['total_toffoli_like'],
                      'conditioned': res['conditioned_toffoli_like']}))


def step_gen_compare(data: Path) -> None:
    import kickmix as km
    sys.path.insert(0, str(data / 'verifiers' / 'dqi'))
    import dqi_reference_circuit as ref
    t0 = time.time()
    mnb = [int(x) for x in os.environ.get('EXP003_MNB', '4095,70,12').split(',')]  # smoke-test override
    g = ref.build_reference_circuit(*mnb)
    build_s = time.time() - t0
    ginfo = {'build_s': round(build_s, 1), 'canonical_sha256': canonical_sha(g), **stats_dict(g)}
    s = km.Circuit.from_file(str(data / 'sample_submission' / 'dqi.kmb'))
    sinfo = {'canonical_sha256': canonical_sha(s), **stats_dict(s)}
    equal = bool(g == s)
    del s
    res = tag_count(g, 'generator')
    assert res['total_toffoli_like'] == ginfo['num_toffoli_like']
    out = {'generator': ginfo, 'sample': sinfo, 'circuit_equal': equal,
           'canonical_sha_equal': ginfo['canonical_sha256'] == sinfo['canonical_sha256'],
           'op_counts_equal': ginfo['op_counts'] == sinfo['op_counts'],
           'generator_source_sha256': sha256_file(data / 'verifiers' / 'dqi' / 'dqi_reference_circuit.py')}
    (OUT / 'gen_compare.json').write_text(json.dumps(out, indent=1))
    (OUT / 'generator_count.json').write_text(json.dumps(res, indent=1))
    print(json.dumps({k: out[k] for k in ('circuit_equal', 'canonical_sha_equal', 'op_counts_equal')}))


def proc_hwm(p) -> int:
    try:
        with open(f'/proc/{p.pid}/status') as f:
            for line in f:
                if line.startswith('VmHWM:'):
                    return int(line.split()[1]) * 1024
    except OSError:
        pass
    try:
        return int(getattr(p.memory_info(), 'peak_wset', 0) or 0)
    except Exception:
        return 0


def run_child(label: str, cmd: list[str]) -> dict:
    import psutil
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', PYTHONUNBUFFERED='1',
               EXP003_OUT=str(OUT), EXP003_TMP=str(TMP))
    so, se = OUT / f'{label}.stdout.txt', OUT / f'{label}.stderr.log'
    peaks = {'tree_rss_peak_bytes': 0, 'proc_hwm_peak_bytes': 0, 'sys_used_peak_bytes': 0}
    t0 = time.time()
    with open(so, 'wb') as fo, open(se, 'wb') as fe:
        child = subprocess.Popen(cmd, stdout=fo, stderr=fe, env=env, cwd=str(OUT))
        root = psutil.Process(child.pid)
        stop = threading.Event()

        def poll() -> None:
            while not stop.is_set():
                try:
                    procs = [root] + root.children(recursive=True)
                except psutil.Error:
                    procs = []
                rss = 0
                for p in procs:
                    try:
                        rss += p.memory_info().rss
                    except psutil.Error:
                        pass
                    peaks['proc_hwm_peak_bytes'] = max(peaks['proc_hwm_peak_bytes'], proc_hwm(p))
                peaks['tree_rss_peak_bytes'] = max(peaks['tree_rss_peak_bytes'], rss)
                peaks['sys_used_peak_bytes'] = max(peaks['sys_used_peak_bytes'],
                                                   psutil.virtual_memory().used)
                stop.wait(POLL_S)

        th = threading.Thread(target=poll, daemon=True)
        th.start()
        rc = child.wait()
        stop.set()
        th.join()
    text = so.read_text(errors='replace')
    parsed = None
    if '{' in text:
        try:
            parsed = json.loads(text[text.index('{'):])
        except ValueError:
            parsed = None
    rec = {'label': label, 'cmd': cmd, 'returncode': rc, 'wall_s': round(time.time() - t0, 1),
           **peaks, 'output': parsed}
    print(json.dumps({k: rec[k] for k in ('label', 'returncode', 'wall_s', 'proc_hwm_peak_bytes')}),
          flush=True)
    return rec


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--step', default=None)
    ap.add_argument('--data-root', type=Path, default=None)
    ap.add_argument('--skip-verify', action='store_true')
    args = ap.parse_args()
    data = (args.data_root or find_data_root()).resolve()
    OUT.mkdir(parents=True, exist_ok=True)
    if args.step == 'sample_count':
        return step_sample_count(data)
    if args.step == 'gen_compare':
        return step_gen_compare(data)

    if ON_KAGGLE:
        subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', KICKMIX_PIN], check=True)
    from importlib.metadata import version
    info = {'platform': platform.platform(), 'python': sys.version, 'cpu_count': os.cpu_count(),
            'kickmix': version('kickmix'), 'numpy': version('numpy'), 'data_root': str(data),
            'verifier_sha256': sha256_file(data / 'verifiers' / 'dqi' / 'verify_submission_dqi.py'),
            'sample_dqi_sha256': sha256_file(data / 'sample_submission' / 'dqi.kmb')}
    me = str(Path(__file__).resolve())
    runs = [run_child('sample_count', [sys.executable, me, '--step', 'sample_count',
                                       '--data-root', str(data)]),
            run_child('gen_compare', [sys.executable, me, '--step', 'gen_compare',
                                      '--data-root', str(data)])]
    if not args.skip_verify:
        verifier = str(data / 'verifiers' / 'dqi' / 'verify_submission_dqi.py')
        sample = str(data / 'sample_submission' / 'dqi.kmb')
        for salt in SALTS:
            runs.append(run_child(f'dqi_salt_{salt}',
                                  [sys.executable, verifier, sample, '--salt', salt]))
    (OUT / 'runs.json').write_text(json.dumps({'machine': info, 'runs': runs}, indent=1))
    print('done', flush=True)


if __name__ == '__main__':
    main()
