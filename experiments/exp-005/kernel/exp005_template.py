import glob
import hashlib
import io
import json
import lzma
import os
import platform
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path

ON_KAGGLE = Path('/kaggle/working').is_dir()
POLL_S = 0.5
KICKMIX_PIN = 'kickmix==1.0.0'
SALTS = ['exp005-a', 'exp005-b', 'exp005-c']
SEG_WORKERS = 4
SEG_SHOTS = int(os.environ.get('EXP005_SEG_SHOTS', '2048'))  # override for the local smoke test only
SEG_SEED0 = 5005000
EXPECTED_XZ_SHA = '07db71ee28c1d3bfaf2496c92dd7153eb0d01ced3797a8d95502ccf0fa541c33'
EXPECTED_KMB_SHA = '4ee7a17b4cbca4053a19bc951e7f2ef91fabdbb036006c9d658adcff4fe76da4'
EXCERPT_MAX_LINES = 6000
OUT = Path(os.environ.get('EXP005_OUT') or ('/kaggle/working/exp005' if ON_KAGGLE else 'exp005_local_out')).resolve()
TMP = Path(os.environ.get('EXP005_TMP') or ('/tmp/exp005' if ON_KAGGLE else 'exp005_local_tmp')).resolve()
KMB = TMP / 'dqi.kmb'
KMX = TMP / 'dqi.kmx'

COUNTER_SRC = __COUNTER_SRC__
SEGSIM_SRC = __SEGSIM_SRC__


def load_src(name: str, src: str):
    import types
    mod = types.ModuleType(name)
    exec(compile(src, f'{name}.py', 'exec'), mod.__dict__)
    return mod


def find_data_root() -> Path:
    marker = Path('verifiers') / 'dqi' / 'verify_submission_dqi.py'
    for dirpath, dirnames, _ in os.walk('/kaggle/input'):
        if (Path(dirpath) / marker).is_file():
            return Path(dirpath)
        if dirpath.count(os.sep) > 6:
            dirnames[:] = []
    raise FileNotFoundError('competition data not found under /kaggle/input')


def find_dataset() -> Path:
    hits = [h for h in glob.glob('/kaggle/input/**/QCC_RELEASE_MANIFEST.json', recursive=True)
            if Path(h).with_name('dqi.kmb.xz').is_file()]
    if len(hits) != 1:
        raise FileNotFoundError(f'expected one release dataset, found {hits}')
    return Path(hits[0]).parent


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 22), b''):
            h.update(chunk)
    return h.hexdigest()


def canonical_sha(circuit) -> str:
    buf = io.BytesIO()
    circuit.to_file(buf, format='kmb')
    return hashlib.sha256(buf.getvalue()).hexdigest()


def stats_dict(circuit) -> dict:
    s = circuit.operation_statistics()
    return {'num_qubits': circuit.num_qubits, 'num_bits': circuit.num_bits,
            'num_registers': circuit.num_registers,
            'num_toffoli_like': s.num_toffoli_like, 'num_t_like': s.num_t_like,
            'num_instructions': s.num_instructions, 'op_counts': dict(s)}


def step_prepare(data: Path) -> None:
    ds = find_dataset()
    xz = ds / 'dqi.kmb.xz'
    manifest = json.loads((ds / 'QCC_RELEASE_MANIFEST.json').read_text())
    entry = next(e for e in manifest['files'] if e['file'] == 'dqi.kmb')
    info = {'dataset_dir': str(ds), 'xz_sha256': sha256_file(xz), 'xz_bytes': xz.stat().st_size,
            'manifest_portfolio': manifest.get('portfolio'), 'manifest_dqi_sha256': entry['sha256'],
            'manifest_sha256': sha256_file(ds / 'QCC_RELEASE_MANIFEST.json'),
            'dataset_listing': sorted(os.listdir(ds))}
    if info['xz_sha256'] != EXPECTED_XZ_SHA:
        raise SystemExit(f'dataset dqi.kmb.xz differs from the local download: {info}')
    TMP.mkdir(parents=True, exist_ok=True)
    with lzma.open(xz) as fi, open(KMB, 'wb') as fo:
        shutil.copyfileobj(fi, fo, 1 << 22)
    info['kmb_sha256'] = sha256_file(KMB)
    info['kmb_bytes'] = KMB.stat().st_size
    if info['kmb_sha256'] != EXPECTED_KMB_SHA or info['kmb_sha256'] != entry['sha256']:
        raise SystemExit(f'decompressed dqi.kmb hash mismatch: {info}')
    (OUT / 'prepare.json').write_text(json.dumps(info, indent=1))
    print(json.dumps({k: info[k] for k in ('xz_sha256', 'kmb_sha256', 'manifest_portfolio')}))


def write_excerpts(kmx: Path, outdir: Path) -> dict:
    """First instance of every tag name (nesting-aware, capped), plus the first instruction lines."""
    outdir.mkdir(parents=True, exist_ok=True)
    seen: set[str] = set()
    open_caps: list[list] = []    # [name, depth_at_enter, lines]
    head: list[str] = []
    depth = 0
    index = {}
    with open(kmx, encoding='utf-8') as f:
        for line in f:
            op = line.split(' ', 1)[0].rstrip('\n')
            if op in ('REGISTER', 'APPEND_TO_REGISTER'):
                continue
            if len(head) < EXCERPT_MAX_LINES:
                head.append(line)
            is_tag = op == 'INFO_TAG'
            if is_tag:
                tag = line.split('"', 2)[1]
                if tag.startswith('@enter:'):
                    name = tag[7:]
                    depth += 1
                    if name not in seen:
                        seen.add(name)
                        open_caps.append([name, depth, []])
            for cap in open_caps:
                if len(cap[2]) < EXCERPT_MAX_LINES:
                    cap[2].append(line)
            if is_tag and tag.startswith('@exit:'):
                done = [c for c in open_caps if c[1] == depth]
                for c in done:
                    fn = ''.join(ch if ch.isalnum() or ch in '-_' else '_' for ch in c[0])[:80]
                    (outdir / f'{fn}.kmx').write_text(''.join(c[2]))
                    index[c[0]] = {'file': f'{fn}.kmx', 'lines': len(c[2])}
                    open_caps.remove(c)
                depth -= 1
    (outdir / 'head.kmx').write_text(''.join(head))
    return index


def step_count(data: Path) -> None:
    import kickmix as km
    counter = load_src('kmx_tag_count', COUNTER_SRC)
    t0 = time.time()
    c = km.Circuit.from_file(str(KMB))
    load_s = time.time() - t0
    info = {'load_s': round(load_s, 1), 'canonical_sha256': canonical_sha(c), **stats_dict(c),
            'reaction_depth': c.reaction_depth()}
    regs = c.register_data
    info['register_names_sample'] = sorted(regs)[:5] + sorted(regs)[-5:]
    t1 = time.time()
    c.to_file(str(KMX), format='kmx')
    info['kmx_write_s'] = round(time.time() - t1, 1)
    info['kmx_bytes'] = KMX.stat().st_size
    del c
    t2 = time.time()
    res = counter.count(str(KMX))
    res['count_s'] = round(time.time() - t2, 1)
    res['circuit_info'] = info
    res['counter_total_matches_stats'] = res['total_toffoli_like'] == info['num_toffoli_like']
    t3 = time.time()
    res['excerpts'] = write_excerpts(KMX, OUT / 'excerpts')
    res['excerpt_s'] = round(time.time() - t3, 1)
    (OUT / 'count.json').write_text(json.dumps(res, indent=1))
    print(json.dumps({'q': info['num_qubits'], 'static_toffoli': info['num_toffoli_like'],
                      'tag_total': res['total_toffoli_like'],
                      'conditioned': res['conditioned_toffoli_like'],
                      'n_tag_names': len(res['instance_histograms'])}))


def step_segsim(data: Path, worker: int) -> None:
    import numpy as np
    import kickmix as km
    sys.path.insert(0, str(data / 'verifiers' / 'dqi'))
    import verify_submission_dqi as v
    seg = load_src('kmx_segment_sim', SEGSIM_SRC)
    c = km.Circuit.from_file(str(KMB))
    mn = os.environ.get('EXP005_SPEC_MN')  # local smoke test only, e.g. '20,6'; unset on Kaggle
    spec = (v.ProblemSpecDQI.benchmark_instance(m=int(mn.split(',')[0]), n=int(mn.split(',')[1]))
            if mn else v.ProblemSpecDQI.benchmark_instance())
    tables = v.FieldTables(km.GF2Field(spec.degree))
    weight_probs = v.optimal_dqi_weights(spec.m, spec.max_errors, spec.degree, spec.r) ** 2
    seed = SEG_SEED0 + worker
    rng = np.random.default_rng(seed)
    syndromes, mbuc, phases = v.sample_shots(spec, tables, rng, SEG_SHOTS, weight_probs)
    syn_q, mbuc_b, anc = v.validate_registers(c, spec)
    syn_a, mbuc_a = km.array(syn_q), km.array(mbuc_b)
    in_syn = v.to_bits(syndromes, spec.degree)

    def fresh():
        sim = km.Simulator(batch_size=SEG_SHOTS, debug_print=False, counting_operations=True, seed=seed)
        sim.use_same_registers_as(c)
        sim.write_across_shots(syn_a, in_syn)
        sim.write_across_shots(mbuc_a, v.to_bits(mbuc, spec.degree))
        return sim

    def check(sim):
        flipped = sim.read_phase_flipped_across_shots()
        diff = sim.read_across_shots(syn_a) ^ in_syn
        junk = sim.read_across_shots(anc) if len(anc) else np.zeros((0, SEG_SHOTS), dtype=bool)
        val = diff.any(axis=0) | junk.any(axis=0)
        ph = (flipped ^ phases) & ~val
        allq = sim.read_across_shots(km.array([km.q(k) for k in range(c.num_qubits)]))
        return int(val.sum()), int(ph.sum()), flipped, allq

    t0 = time.time()
    a = fresh()
    a.do(c)
    full_tof = int(a.operation_statistics().num_toffoli_like)
    va, pa, fa, qa = check(a)
    full_s = time.time() - t0
    del a
    b = fresh()
    res = seg.run_segmented(str(KMX), b, km=km)
    vb, pb, fb, qb = check(b)
    weights = np.bitwise_or.reduce(syndromes != 0, axis=1)
    res.update({'worker': worker, 'seed': seed, 'full_run_s': round(full_s, 1),
                'full_toffoli': full_tof, 'full_value_errors': va, 'full_phase_errors': pa,
                'seg_value_errors': vb, 'seg_phase_errors': pb,
                'phase_equal': bool(np.array_equal(fa, fb)), 'qubits_equal': bool(np.array_equal(qa, qb)),
                'toffoli_equal': full_tof == res['total_executed_toffoli'],
                'shots_with_nonzero_syndrome': int(weights.sum())})
    (OUT / f'segsim_{worker}.json').write_text(json.dumps(res, indent=1))
    print(json.dumps({k: res[k] for k in ('worker', 'toffoli_equal', 'phase_equal', 'qubits_equal',
                                          'full_value_errors', 'full_phase_errors', 'per_shot_total',
                                          'inexact_executed_fraction', 'segments', 'wall_s')}))


def proc_hwm(p) -> int:
    try:
        with open(f'/proc/{p.pid}/status') as f:
            for line in f:
                if line.startswith('VmHWM:'):
                    return int(line.split()[1]) * 1024
    except OSError:
        pass
    return 0


def run_children(jobs: list[tuple[str, list[str]]]) -> list[dict]:
    """Starts all jobs at once; returns one record per job, with peaks sampled over the group."""
    import psutil
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', PYTHONUNBUFFERED='1',
               EXP005_OUT=str(OUT), EXP005_TMP=str(TMP))
    t0 = time.time()
    procs, files = [], []
    for label, cmd in jobs:
        fo = open(OUT / f'{label}.stdout.txt', 'wb')
        fe = open(OUT / f'{label}.stderr.log', 'wb')
        files += [fo, fe]
        procs.append(subprocess.Popen(cmd, stdout=fo, stderr=fe, env=env, cwd=str(OUT)))
    peaks = [{'tree_rss_peak_bytes': 0, 'proc_hwm_peak_bytes': 0} for _ in jobs]
    group = {'sys_used_peak_bytes': 0}
    walls = [None] * len(jobs)
    stop = threading.Event()

    def poll() -> None:
        while not stop.is_set():
            for i, child in enumerate(procs):
                try:
                    root = psutil.Process(child.pid)
                    ps = [root] + root.children(recursive=True)
                except psutil.Error:
                    continue
                rss = 0
                for p in ps:
                    try:
                        rss += p.memory_info().rss
                    except psutil.Error:
                        pass
                    peaks[i]['proc_hwm_peak_bytes'] = max(peaks[i]['proc_hwm_peak_bytes'], proc_hwm(p))
                peaks[i]['tree_rss_peak_bytes'] = max(peaks[i]['tree_rss_peak_bytes'], rss)
            group['sys_used_peak_bytes'] = max(group['sys_used_peak_bytes'], psutil.virtual_memory().used)
            stop.wait(POLL_S)

    th = threading.Thread(target=poll, daemon=True)
    th.start()
    rcs = []
    for i, child in enumerate(procs):
        rcs.append(child.wait())
        walls[i] = round(time.time() - t0, 1)
    stop.set()
    th.join()
    for fh in files:
        fh.close()
    recs = []
    for i, (label, cmd) in enumerate(jobs):
        text = (OUT / f'{label}.stdout.txt').read_text(errors='replace')
        parsed = None
        if '{' in text:
            try:
                parsed = json.loads(text[text.index('{'):])
            except ValueError:
                parsed = None
        rec = {'label': label, 'cmd': cmd, 'returncode': rcs[i], 'wall_s': walls[i], **peaks[i],
               'group_sys_used_peak_bytes': group['sys_used_peak_bytes'], 'output': parsed}
        print(json.dumps({k: rec[k] for k in ('label', 'returncode', 'wall_s', 'proc_hwm_peak_bytes')}),
              flush=True)
        recs.append(rec)
    return recs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--step', default=None)
    ap.add_argument('--worker', type=int, default=0)
    ap.add_argument('--data-root', type=Path, default=None)
    ap.add_argument('--skip-verify', action='store_true')
    args = ap.parse_args()
    data = (args.data_root or find_data_root()).resolve()
    OUT.mkdir(parents=True, exist_ok=True)
    if args.step == 'prepare':
        return step_prepare(data)
    if args.step == 'count':
        return step_count(data)
    if args.step == 'segsim':
        return step_segsim(data, args.worker)

    if ON_KAGGLE:
        subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', KICKMIX_PIN], check=True)
    from importlib.metadata import version
    info = {'platform': platform.platform(), 'python': sys.version, 'cpu_count': os.cpu_count(),
            'kickmix': version('kickmix'), 'numpy': version('numpy'), 'data_root': str(data),
            'verifier_sha256': sha256_file(data / 'verifiers' / 'dqi' / 'verify_submission_dqi.py')}
    me = str(Path(__file__).resolve())
    base = [sys.executable, me, '--data-root', str(data)]
    runs = []
    log = lambda: (OUT / 'runs.json').write_text(json.dumps({'machine': info, 'runs': runs}, indent=1))
    runs += run_children([('prepare', base + ['--step', 'prepare'])])
    log()
    if runs[-1]['returncode'] != 0:
        print('prepare failed', flush=True)
        return
    runs += run_children([('count', base + ['--step', 'count'])])
    log()
    runs += run_children([(f'segsim_{k}', base + ['--step', 'segsim', '--worker', str(k)])
                          for k in range(SEG_WORKERS)])
    log()
    if not args.skip_verify:
        verifier = str(data / 'verifiers' / 'dqi' / 'verify_submission_dqi.py')
        for salt in SALTS:
            runs += run_children([(f'dqi_salt_{salt}', [sys.executable, verifier, str(KMB), '--salt', salt])])
            log()
    print('done', flush=True)


if __name__ == '__main__':
    main()
