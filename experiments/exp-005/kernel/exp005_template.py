"""exp-005: Toffoli accounting of the public heliosli/SomeJoint dqi decoder (measurement only).

Self-contained private Kaggle script kernel, generated by build_kernel.py, which inlines
src/kmx_tag_count.py and src/kmx_segment_sim.py. It never calls any Kaggle API and never submits.
The downloaded circuit is loaded only through kickmix (Circuit.from_file). No downloaded code runs.

Steps (each in its own child process, memory sampled by the parent):
  prepare   find dataset, check dqi.kmb.xz SHA-256 = local download, decompress, check manifest SHA-256
  count     load, stats, canonical sha, dump .kmx, run the tag counter, write excerpts per tag name
  segsim_k  k = 0..3: 2,048 verifier-distributed shots each (official sample_shots, fixed seeds),
            segmented simulation per tag path, plus a whole-circuit run on the same inputs to check it
  dqi_salt  unmodified official verifier, --salt exp005-a / -b / -c
"""
from __future__ import annotations

