"""exp-010: assemble results.json from the ledger outputs (no verifier run in this experiment).

Usage: python -I -B experiments/exp-010/make_results.py <commit>
Inputs (gitignored, regenerated by port_ledger.py and kmx_ledger.py):
  out/port_ledger.json, out/port_kmx_ledger.json, out/frontier_ledger.json
"""
import collections
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def load(name):
    with open(HERE / 'out' / name, encoding='utf-8') as f:
        return json.load(f)


def seg_table(d):
    return [{k: s[k] for k in ('name', 'lines', 'max_live', 'max_line', 'classes_by_reg_at_max', 'idle_in_segment_at_max',
                               'idle_classes', 'toffoli_static', 'toffoli_exec_mean')} for s in d['segments']]


def window_table(d):
    out = []
    for w in d['phase_windows']:
        feed = collections.Counter()
        for f in w['feeders']:
            c = f['cls_at_start']['cls']
            if c in ('flag', 'xn', 'x', 'const'):
                role = 'flag_or_x'
            elif not f['live_at_start']:
                role = 'phase_only'
            else:
                role = 'data'
            feed[f"{role}|{'x' if f['reg'] else '-'}|{c}"] += 1
        out.append({k: w.get(k) for k in ('temp', 'start', 'first_zpow', 'end', 'n_zpow', 'n_zpow_on_temp', 'live_at_start',
                                           'live_at_first_zpow', 'live_after_end', 'persistent_through_window',
                                           'persistent_classes_by_reg', 'classes_by_reg_at_first_zpow')}
                   | {'feeders_by_role': dict(sorted(feed.items())), 'feeder_summary': w['feeder_summary']})
    return out


# Frontier phases: line ranges chosen by reading its class timeline (kmx_ledger --every=250) and the
# Z_POW groups; they are labels for the report, not something the circuit declares.
FRONTIER_PHASES = [
    ('normalize (flags into x low bits)', 1, 250),
    ('main lookup (35 table qubits)', 251, 16710),
    ('H phase (Z_POW group 1)', 16711, 17090),
    ('table/address step (x[14..21] partly zeroed)', 17091, 22000),
    ('arithmetic (L built, table words erased)', 22001, 27124),
    ('L phase (Z_POW group 2)', 27125, 27380),
    ('arithmetic uncompute', 27381, 31750),
    ('table recompute and uncompute', 31751, 36250),
    ('measured-unlookup phase fix-up', 36251, 43250),
    ('restore address and un-normalize', 43251, 45745),
]


def phase_table(d, kmx_path):
    tof = []
    with open(kmx_path, encoding='utf-8') as f:
        for i, line in enumerate(f, 1):
            op = line.split(' ', 1)[0].strip()
            if op in ('CCX', 'CCZ', 'CSWAP'):
                tof.append(i)
    out = []
    for name, lo, hi in FRONTIER_PHASES:
        mx = max(v for a, b, v in d['live_profile_rle'] if b >= lo and a <= hi)
        pts = [e for e in d['timeline'] if lo <= e['line'] <= hi]
        best = max(pts, key=lambda e: e['live']) if pts else None
        out.append({'phase': name, 'lines': [lo, hi], 'max_live': mx,
                    'toffoli_static': sum(1 for i in tof if lo <= i <= hi),
                    'timeline_point': best['line'] if best else None,
                    'classes_by_reg_at_point': best['classes_by_reg'] if best else None,
                    'live_at_point': best['live'] if best else None})
    return out


def main(commit):
    pl = load('port_ledger.json')
    pk = load('port_kmx_ledger.json')
    fr = load('frontier_ledger.json')
    st = pl['stages']
    stages = {lab: {k: v[k] for k in ('peak', 'peak_sub', 'regs_at_peak', 'internal_at_peak', 'idle_in_stage_at_peak',
                                      'idle_qubits_in_stage_at_peak', 'n_substages_at_peak', 'toffoli_like_calls')}
              for lab, v in st.items() if lab}
    b_rows = [s for s in pl['substages'] if s['label'] in ('B', 'B-1') and 'row' in s['sub'] and 'add' in s['sub']]
    C = 1619.3250243907166      # exp-008 verifier: C of the port
    res = {
        'exp': 'exp-010', 'commit': commit, 'task': 'invsqrt',
        'verifier': None, 'verifier_cmd': None, 'passed': None,
        'note': 'diagnostic width ledger; no official verifier run (none needed). Q/C figures of the port are exp-008 verifier values.',
        'port': {
            'config': 'experiments/exp-008/config_port.json', 'code': 'src/invsqrt at 46af961 (unchanged)',
            'raw_sha256': pl['raw_sha256'], 'final_sha256': pl['final_sha256'],
            'same_circuit_as_exp008': pl['raw_sha256'].startswith('c97569f5') and pl['final_sha256'].startswith('ff629b09'),
            'generator_peak': pl['generator_peak'], 'build_seconds': pl['build_seconds'],
            'stages': stages,
            'B_row_adds': len(b_rows), 'B_row_adds_at_92': sum(1 for s in b_rows if s['total'] == 92),
            'kmx_ledger': {'peak_live': pk['peak_live'], 'segments': seg_table(pk), 'phase_windows': window_table(pk),
                           'toffoli_exec_mean': pk['toffoli_exec_mean'], 'toffoli_exec_frac_at_ge': pk['toffoli_exec_frac_at_ge'],
                           'x_restored': pk['x_restored'], 'seconds': pk['seconds']},
        },
        'frontier': {
            'kmb_sha256': '07314803a0925970cf45007ebbdb8a146378c242e3991c70d6f7509af3d583da',
            'kmx': 'experiments/exp-010/out/public/frontier.kmx (kickmix 1.0.0 from_file/to_file; SHA-256 17019b15...)',
            'peak_live': fr['peak_live'], 'toffoli_static': fr['toffoli_static'], 'toffoli_exec_mean': fr['toffoli_exec_mean'],
            'toffoli_exec_frac_at_ge': fr['toffoli_exec_frac_at_ge'], 'x_restored': fr['x_restored'],
            'segments': seg_table(fr), 'phase_windows': window_table(fr), 'seconds': fr['seconds'],
            'phases': phase_table(fr, HERE / 'out' / 'public' / 'frontier.kmx'),
        },
        'break_even_toffoli_per_qubit_at_Q92': round(C / 92, 2),
    }
    with open(HERE / 'results.json', 'w', encoding='utf-8') as f:
        json.dump(res, f, indent=1)
    print(json.dumps(res, indent=1)[:6000])


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main(sys.argv[1] if len(sys.argv) > 1 else 'pending')
