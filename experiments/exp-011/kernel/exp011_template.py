"""exp-011: build the ported SomeJoint 897-qubit dqi decoder with src/dqi (Apache-2.0 port of SomeJoint v14, not our design; see src/dqi/NOTICE) and verify it.

Self-contained private Kaggle script kernel, generated by make_kernel.py, which embeds src/dqi as a
base64 zip with the SHA-256 of every member. It never calls any Kaggle API and never submits. No
downloaded circuit is read: the only circuit is the one src/dqi builds here. Runs on Kaggle only (user decision
2026-10-29: ported code may not run locally).

Steps (each in its own child process, memory sampled by the parent):
  unpack          decode the zip, check member paths and SHA-256 (generate.py re-checks MANIFEST.json)
  build           python -I -B src/dqi/generate.py /tmp/exp011/dqi.kmb
  stats           kickmix load: Q, operation_statistics, canonical SHA-256; compare with b3354f60 / 53d8b2ed
  dump            to_file(kmx), lzma preset 6 -> /kaggle/working/exp011/dqi.kmx.xz (for local anatomy)
  verify_default  official verifier, no salt
  verify_salt     official verifier, --salt exp011-a
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import lzma
import os
import platform
import subprocess
import sys
import threading
import time
import zipfile
from pathlib import Path, PurePosixPath

ON_KAGGLE = Path('/kaggle/working').is_dir()
POLL_S = 0.5
KICKMIX_PIN = 'kickmix==1.0.0'
SALT = 'exp011-a'
UPSTREAM_897 = 'b3354f60e459dcebe67910363e96498f8bb0aa7f699bc016ef962015c3732fd6'
V15_FILE = '53d8b2edf251e2a0c54c401a97d1396c7ed309e1cbfaab8d54a2c99a11ed6552'
OUT = Path('/kaggle/working/exp011' if ON_KAGGLE else 'exp011_local_out').resolve()
TMP = Path('/tmp/exp011' if ON_KAGGLE else 'exp011_local_tmp').resolve()
SRC = TMP / 'src'
KMB = TMP / 'dqi.kmb'
KMX = TMP / 'dqi.kmx'

SRC_ZIP_B64 = __SRC_ZIP_B64__
SRC_MEMBERS = __SRC_MEMBERS__


def find_data_root() -> Path:
    marker = Path('verifiers') / 'dqi' / 'verify_submission_dqi.py'
    for dirpath, dirnames, _ in os.walk('/kaggle/input'):
        if (Path(dirpath) / marker).is_file():
            return Path(dirpath)
        if dirpath.count(os.sep) > 6:
            dirnames[:] = []
    raise FileNotFoundError('competition data not found under /kaggle/input')


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 22), b''):
            h.update(chunk)
    return h.hexdigest()


def step_unpack() -> None:
    raw = base64.b64decode(SRC_ZIP_B64)
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        names = z.namelist()
        assert sorted(names) == sorted(SRC_MEMBERS), 'zip members differ from the embedded list'
        for n in names:
            p = PurePosixPath(n)
            assert not p.is_absolute() and '..' not in p.parts and p.parts[0] == 'dqi', n
            data = z.read(n)
            assert hashlib.sha256(data).hexdigest() == SRC_MEMBERS[n], n
            dst = SRC / n
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(data)
    print(json.dumps({'unpacked': len(names), 'zip_sha256': hashlib.sha256(raw).hexdigest()}), flush=True)


def step_stats() -> None:
    import kickmix as km
    t0 = time.time()
    c = km.Circuit.from_file(str(KMB))
    t_load = time.time() - t0
    buf = io.BytesIO()
    c.to_file(buf, format='kmb')
    canon = hashlib.sha256(buf.getvalue()).hexdigest()
    s = c.operation_statistics()
    file_sha = sha256_file(KMB)
    rec = {'file_sha256': file_sha, 'canonical_sha256': canon, 'file_bytes': KMB.stat().st_size,
           'equals_b3354f60': file_sha == UPSTREAM_897, 'canonical_equals_b3354f60': canon == UPSTREAM_897,
           'equals_v15_53d8b2ed': file_sha == V15_FILE, 'num_qubits': c.num_qubits, 'num_bits': c.num_bits,
           'num_registers': c.num_registers, 'num_ops': len(c), 'num_toffoli_like': s.num_toffoli_like,
           'num_t_like': s.num_t_like, 'op_counts': dict(s), 'load_s': round(t_load, 1)}
    (OUT / 'stats.json').write_text(json.dumps(rec, indent=1) + '\n')
    print(json.dumps(rec), flush=True)


def step_dump() -> None:
    import kickmix as km
    t0 = time.time()
    c = km.Circuit.from_file(str(KMB))
    c.to_file(str(KMX), format='kmx')
    del c
    t1 = time.time()
    xz = OUT / 'dqi.kmx.xz'
    h = hashlib.sha256()
    with open(KMX, 'rb') as fi, lzma.open(xz, 'wb', preset=6) as fo:
        for chunk in iter(lambda: fi.read(1 << 22), b''):
            h.update(chunk)
            fo.write(chunk)
    rec = {'kmx_bytes': KMX.stat().st_size, 'kmx_sha256': h.hexdigest(), 'xz_bytes': xz.stat().st_size,
           'xz_sha256': sha256_file(xz), 'to_kmx_s': round(t1 - t0, 1), 'xz_s': round(time.time() - t1, 1)}
    KMX.unlink()
    (OUT / 'dump.json').write_text(json.dumps(rec, indent=1) + '\n')
    print(json.dumps(rec), flush=True)


def proc_hwm(p) -> int:
    try:
        with open(f'/proc/{p.pid}/status') as f:
            for line in f:
                if line.startswith('VmHWM:'):
                    return int(line.split()[1]) * 1024
    except OSError:
        pass
    return 0


def run_child(label: str, cmd: list[str], cwd: Path) -> dict:
    """Runs one job; returns its record, with memory peaks sampled over its process tree."""
    import psutil
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', PYTHONUNBUFFERED='1')
    t0 = time.time()
    with open(OUT / f'{label}.stdout.txt', 'wb') as fo, open(OUT / f'{label}.stderr.log', 'wb') as fe:
        child = subprocess.Popen(cmd, stdout=fo, stderr=fe, env=env, cwd=str(cwd))
        peak = {'tree_rss_peak_bytes': 0, 'proc_hwm_peak_bytes': 0, 'sys_used_peak_bytes': 0}
        stop = threading.Event()

        def poll() -> None:
            while not stop.is_set():
                try:
                    root = psutil.Process(child.pid)
                    ps = [root] + root.children(recursive=True)
                except psutil.Error:
                    ps = []
                rss = 0
                for p in ps:
                    try:
                        rss += p.memory_info().rss
                    except psutil.Error:
                        pass
                    peak['proc_hwm_peak_bytes'] = max(peak['proc_hwm_peak_bytes'], proc_hwm(p))
                peak['tree_rss_peak_bytes'] = max(peak['tree_rss_peak_bytes'], rss)
                peak['sys_used_peak_bytes'] = max(peak['sys_used_peak_bytes'], psutil.virtual_memory().used)
                stop.wait(POLL_S)

        th = threading.Thread(target=poll, daemon=True)
        th.start()
        rc = child.wait()
        wall = round(time.time() - t0, 1)
        stop.set()
        th.join()
    text = (OUT / f'{label}.stdout.txt').read_text(errors='replace')
    parsed = None
    if '{' in text:
        try:
            parsed = json.loads(text[text.index('{'):])
        except ValueError:
            parsed = None
    rec = {'label': label, 'cmd': cmd, 'returncode': rc, 'wall_s': wall, **peak, 'output': parsed}
    print(json.dumps({k: rec[k] for k in ('label', 'returncode', 'wall_s', 'proc_hwm_peak_bytes')}), flush=True)
    return rec


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--step', default=None)
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    TMP.mkdir(parents=True, exist_ok=True)
    if args.step == 'unpack':
        return step_unpack()
    if args.step == 'stats':
        return step_stats()
    if args.step == 'dump':
        return step_dump()

    if ON_KAGGLE:
        subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', KICKMIX_PIN], check=True)
    from importlib.metadata import version
    data = find_data_root().resolve()
    verifier = data / 'verifiers' / 'dqi' / 'verify_submission_dqi.py'
    info = {'platform': platform.platform(), 'python': sys.version, 'cpu_count': os.cpu_count(),
            'kickmix': version('kickmix'), 'numpy': version('numpy'), 'data_root': str(data),
            'verifier_sha256': sha256_file(verifier)}
    me = str(Path(__file__).resolve())
    runs = []

    def log() -> None:
        (OUT / 'runs.json').write_text(json.dumps({'machine': info, 'runs': runs}, indent=1))

    def step(label, cmd, cwd=OUT) -> bool:
        runs.append(run_child(label, cmd, cwd))
        log()
        return runs[-1]['returncode'] == 0

    py = [sys.executable, '-I', '-B']
    if not step('unpack', [sys.executable, me, '--step', 'unpack']):
        return
    if not step('build', py + [str(SRC / 'dqi' / 'generate.py'), str(KMB)], cwd=TMP):
        return
    build_json = KMB.with_suffix('.build.json')
    (OUT / 'build.json').write_text(build_json.read_text())
    step('stats', [sys.executable, me, '--step', 'stats'])
    step('dump', [sys.executable, me, '--step', 'dump'])
    vcwd = verifier.parent
    step('verify_default', [sys.executable, str(verifier), str(KMB)], cwd=vcwd)
    step('verify_salt', [sys.executable, str(verifier), str(KMB), '--salt', SALT], cwd=vcwd)
    print('done', flush=True)


if __name__ == '__main__':
    main()
