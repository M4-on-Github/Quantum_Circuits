"""Rebuild the logbook INDEX.md files from YAML frontmatter.

Run from anywhere: python scripts/build_index.py
Also runs automatically after every Write/Edit (see .claude/settings.json).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def frontmatter(path: Path) -> dict:
    """Parse a flat YAML frontmatter block: `key: value` and `key: [a, b]`."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return {}
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    meta = {}
    for line in text[3:end].splitlines():
        if ":" not in line or line.startswith((" ", "#")):
            continue
        key, _, value = line.partition(":")
        value = value.strip().strip('"').strip("'")
        if value.startswith("[") and value.endswith("]"):
            value = ", ".join(v.strip().strip('"\'') for v in value[1:-1].split(",") if v.strip())
        meta[key.strip()] = value
    return meta


def table(headers: list[str], rows: list[list[str]]) -> str:
    cell = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def write(path: Path, title: str, sections: list[tuple[str, str]]) -> None:
    body = [f"# {title}", "", "_Generated by scripts/build_index.py. Do not edit by hand._", ""]
    for heading, content in sections:
        body += [f"## {heading}", "", content, ""]
    new = "\n".join(body)
    if not path.exists() or path.read_text(encoding="utf-8") != new:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8")


def rel(p: Path, base: Path) -> str:
    return p.relative_to(base).as_posix()


def literature() -> None:
    base = ROOT / "literature"
    rows = []
    for p in sorted((base / "papers").glob("lit-*.md")):
        m = frontmatter(p)
        rows.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("title", ""), m.get("year", ""),
                     m.get("tasks", ""), m.get("relevance", ""), m.get("read", "")])
    write(base / "INDEX.md", "Literature index",
          [("Papers", table(["ID", "Title", "Year", "Tasks", "Relevance", "Read"], rows))])


def kaggle() -> None:
    base = ROOT / "kaggle"
    digests = []
    for p in sorted((base / "digests").glob("*.md"), reverse=True):
        m = frontmatter(p)
        digests.append([f"[{p.stem}]({rel(p, base)})", m.get("since", ""), m.get("items", ""),
                        m.get("headline", "")])
    threads = []
    for p in sorted((base / "threads").glob("kg-*.md")):
        m = frontmatter(p)
        threads.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("title", ""),
                        m.get("author_role", ""), m.get("credibility", ""), m.get("tasks", ""),
                        m.get("last_checked", "")])
    write(base / "INDEX.md", "Kaggle index", [
        ("Digests", table(["Date", "Since", "Items", "Headline"], digests)),
        ("Threads", table(["ID", "Title", "Author role", "Credibility", "Tasks", "Last checked"], threads)),
    ])


def experiments() -> None:
    base = ROOT / "experiments"
    rows = []
    for d in sorted(p for p in base.glob("exp-*") if p.is_dir()):
        m = frontmatter(d / "README.md")
        verdict = frontmatter(d / "critic.md").get("verdict", "pending")
        rows.append([f"[{m.get('id', d.name)}]({d.name}/README.md)", m.get("title", ""), m.get("task", ""),
                     m.get("tests", ""), m.get("status", ""), m.get("result", ""), verdict])
    write(base / "INDEX.md", "Experiment index",
          [("Experiments", table(["ID", "Title", "Task", "Tests", "Status", "Result", "Critic"], rows))])


def main() -> int:
    literature()
    kaggle()
    experiments()
    return 0


if __name__ == "__main__":
    sys.exit(main())
